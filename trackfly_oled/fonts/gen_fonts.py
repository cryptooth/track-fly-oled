#!/usr/bin/env python3
"""Builds ../fonts.h from Kode Mono with lv_font_conv (npx).

Each font: 4 bits per pixel (antialiased), glyphs sorted by code point.
Run from anywhere:  python3 fonts/gen_fonts.py
"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "fonts.h")

TEXT = "0x20-0x7E,0xA0-0x17F,0x2013-0x2014,0x2018-0x201D,0x2022,0x2026"
#        name          file                 size  ranges
FONTS = [
    ("F_TITLE",  "KodeMonoBold.ttf",    20, TEXT),
    ("F_SUB",    "KodeMonoRegular.ttf", 14, TEXT),
    ("F_META",   "KodeMonoRegular.ttf", 11, TEXT),
    ("F_CLOCK",  "KodeMonoRegular.ttf", 44, "0x20,0x30-0x3A"),
]

def convert(ttf, size, ranges):
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "f.c")
        subprocess.run(["npx", "-y", "lv_font_conv", "--font", os.path.join(HERE, ttf), "-r", ranges,
                        "--size", str(size), "--bpp", "4", "--format", "lvgl", "--no-compress", "-o", c],
                       check=True, stdout=subprocess.DEVNULL)
        return open(c).read()

def parse(src):
    bm_block = src[src.index("glyph_bitmap[] = {"):]
    bm_block = bm_block[:bm_block.index("};")]
    cps, chunks = [], []
    for part in re.split(r"/\* U\+([0-9A-F]+) .*?\*/", bm_block)[1:]:
        if re.fullmatch(r"[0-9A-F]+", part):
            cps.append(int(part, 16))
        else:
            chunks.append([int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", part)])
    dsc = re.findall(r"\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), "
                     r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}", src)[1:]   # id 0 is reserved
    assert len(dsc) == len(cps) == len(chunks), (len(dsc), len(cps), len(chunks))
    lh = int(re.search(r"\.line_height = (\d+)", src).group(1))
    bl = int(re.search(r"\.base_line = (\d+)", src).group(1))
    return cps, chunks, dsc, lh, bl

def main():
    out = ["// Generated by fonts/gen_fonts.py from Kode Mono (SIL Open Font License). Do not edit.",
           "#pragma once", "#include <stdint.h>", '#include "gfx.h"', ""]
    for name, ttf, size, ranges in FONTS:
        cps, chunks, dsc, lh, bl = parse(convert(ttf, size, ranges))
        data, glyphs = [], []
        for cp, chunk, d in zip(cps, chunks, dsc):
            _, adv, w, h, ox, oy = map(int, d)
            adv = (adv + 8) // 16 * 16   # whole pixels: even letter spacing on a 1:1 pixel screen
            glyphs.append(f"{{{len(data)},{adv},{w},{h},{ox},{oy}}}")
            data += chunk
        low = name.lower()
        out.append(f"// {ttf} {size}px, {len(cps)} glyphs, {len(data)} bytes")
        out.append(f"static const uint8_t {low}_bmp[] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const uint16_t {low}_cp[] = {{" + ",".join(str(c) for c in cps) + "};")
        out.append(f"static const Glyph {low}_gl[] = {{" + ",".join(glyphs) + "};")
        # ascent = line height above the baseline
        out.append(f"static const Font {name} = {{ {low}_bmp, {low}_gl, {low}_cp, {len(cps)}, {lh}, {lh - bl} }};")
        out.append("")
    open(OUT, "w").write("\n".join(out))
    print("wrote", os.path.normpath(OUT))

if __name__ == "__main__":
    main()
